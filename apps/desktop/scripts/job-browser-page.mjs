// Builds Classic's page finder (`src/renderer/src/walk-find-page.ts`) into the script the native app's Job browser
// evaluates in a WKContentWorld of its own, so an agent reads the same snapshot and its targets are found the same way
// in either app. `pnpm --filter @armada/desktop job-browser-page` writes it; `job-browser-native-page.test.ts` fails while
// the checked-in copy differs from a fresh build.
//
// It builds a second script beside it: Classic's capture layer (`src/main/capture/page-reader.ts`), which the native
// annotation layer asks for the part of a page at a point, so a note made over a Job's page names its element.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const here = dirname(fileURLToPath(import.meta.url));
export const ENTRY = resolve(here, "../src/renderer/src/walk-find-page.ts");
export const OUT = resolve(here, "../../../crates/bridge-native/src/job_browser/page.js");

export const READER_ENTRY = resolve(here, "../src/main/capture/page-reader.ts");
export const READER_OUT = resolve(here, "../../../crates/bridge-native/src/page_note/read.js");

const head = (from) =>
  `// Generated by apps/desktop/scripts/job-browser-page.mjs from Classic's ${from}. Do not edit.\n`;

/** The script as it should be checked in. */
export async function built() {
  return `${head("walk-find-page.ts")}${await bundled(ENTRY, "ArmadaFinder")}`;
}

/** The page reader as it should be checked in. */
export async function builtReader() {
  return `${head("capture/page-reader.ts")}${await bundled(READER_ENTRY, "ArmadaReader")}`;
}

async function bundled(entry, name) {
  const result = await build({
    configFile: false,
    logLevel: "silent",
    build: {
      write: false,
      minify: true,
      target: "es2022",
      lib: {
        entry,
        name,
        formats: [
          "iife",
        ],
      },
    },
  });
  const chunk = (
    Array.isArray(result)
      ? result
      : [
          result,
        ]
  )
    .flatMap((one) => ("output" in one ? one.output : []))
    .find((one) => one.type === "chunk");
  if (chunk === undefined) throw new Error(`${name} built to nothing`);
  return chunk.code;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, await built());
  mkdirSync(dirname(READER_OUT), {
    recursive: true,
  });
  writeFileSync(READER_OUT, await builtReader());
}
