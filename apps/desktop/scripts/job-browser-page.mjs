// Builds Classic's page finder (`src/renderer/src/walk-find-page.ts`) into the script the native app's Job browser
// evaluates in a WKContentWorld of its own, so an agent reads the same snapshot and its targets are found the same way
// in either app. `pnpm --filter @armada/desktop job-browser-page` writes it; `job-browser-page.test.ts` fails while
// the checked-in copy differs from a fresh build.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const here = dirname(fileURLToPath(import.meta.url));
export const ENTRY = resolve(here, "../src/renderer/src/walk-find-page.ts");
export const OUT = resolve(here, "../../../crates/bridge-native/src/job_browser/page.js");

const HEAD =
  "// Generated by apps/desktop/scripts/job-browser-page.mjs from Classic's walk-find-page.ts. Do not edit.\n";

/** The script as it should be checked in. */
export async function built() {
  const result = await build({
    configFile: false,
    logLevel: "silent",
    build: {
      write: false,
      minify: true,
      target: "es2022",
      lib: {
        entry: ENTRY,
        name: "ArmadaFinder",
        formats: [
          "iife",
        ],
      },
    },
  });
  const chunk = (
    Array.isArray(result)
      ? result
      : [
          result,
        ]
  )
    .flatMap((one) => ("output" in one ? one.output : []))
    .find((one) => one.type === "chunk");
  if (chunk === undefined) throw new Error("the page finder built to nothing");
  return `${HEAD}${chunk.code}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, await built());
}
