/// Every generated file as `(path from the root, contents)`.
pub fn outputs(root: &Path) -> Result<Vec<(String, String)>, String> {
    let mut files = Vec::new();
    walk(&root.join(SOURCE), &mut files).map_err(|e| format!("cannot read {SOURCE}: {e}"))?;
    files.sort();
    let mut items = Vec::new();
    for path in files {
        let rel = path.strip_prefix(root.join(SOURCE)).unwrap_or(&path).with_extension("");
        let rel = rel.to_string_lossy().replace('\\', "/");
        let text = fs::read_to_string(&path).map_err(|e| format!("cannot read {}: {e}", path.display()))?;
        let toks = lex::lex(&text).map_err(|why| format!("{rel}: {why}"))?;
        items.extend(parse::items(toks, &rel)?);
    }
    let reg = emit::Registry { items };
    let closure = reg.closure(ROOTS)?;
    let mut out: Vec<(String, String)> = emit::render(&reg, &closure)?
        .into_iter()
        .map(|(name, text)| (format!("{DIR}/{name}"), text))
        .collect();
    let mut index = String::from("// Generated by `cargo xtask verify-wire --write`. Do not edit.\n\n");
    let mut modules: Vec<&str> = out.iter().map(|(p, _)| p.rsplit('/').next().unwrap_or(p).trim_end_matches(".ts")).collect();
    modules.sort();
    for m in modules {
        index.push_str(&format!("export type * from \"./{m}\";\n"));
    }
    out.push((format!("{DIR}/index.ts"), index));
    Ok(out)
}

/// Files in the wire directory that no type writes any more.
pub fn extras(root: &Path, outputs: &[(String, String)]) -> Vec<String> {
    let want: BTreeSet<&str> = outputs.iter().map(|(p, _)| p.as_str()).collect();
    let mut have = Vec::new();
    if let Ok(dir) = fs::read_dir(root.join(DIR)) {
        for e in dir.flatten() {
            let rel = format!("{DIR}/{}", e.file_name().to_string_lossy());
            if !want.contains(rel.as_str()) {
                have.push(rel);
            }
        }
    }
    have.sort();
    have
}

fn walk(dir: &Path, out: &mut Vec<std::path::PathBuf>) -> std::io::Result<()> {
    for e in fs::read_dir(dir)? {
        let path = e?.path();
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_default();
        if name == "tests" || name == "tests.rs" {
            continue;
        }
        if path.is_dir() {
            walk(&path, out)?;
        } else if path.extension().is_some_and(|x| x == "rs") {
            out.push(path);
        }
    }
    Ok(())
}

/// The gate's half: what is checked in under [`DIR`] is what `crates/ipc` generates.
pub fn pockets_wire_types_are_generated_from_ipc(root: &Path) -> Report {
    let mut report = Report::new("Pocket's wire types are generated from crates/ipc");
    match outputs(root) {
        Err(why) => report.fail(why),
        Ok(outputs) => {
            for (rel, want) in &outputs {
                match fs::read_to_string(root.join(rel)) {
                    Ok(have) if &have == want => {}
                    Ok(_) => report.fail(format!(
                        "{rel} — stale or hand-edited. Run `cargo xtask verify-wire --write` and commit what it emits"
                    )),
                    Err(_) => report.fail(format!("{rel} — not generated yet")),
                }
            }
            for rel in extras(root, &outputs) {
                report.fail(format!(
                    "{rel} — nothing generates it any more. Run `cargo xtask verify-wire --write` and commit what it removes"
                ));
            }
        }
    }
    report
}
