//! Pocket's wire types, generated from the Rust ones in `crates/ipc/src`.
//!
//! **`crates/ipc` is the authority and `apps/pocket/src/wire/` is a copy of the part Pocket reads.**
//! Pocket is the phone app and the one TypeScript client that stays, so it imports these instead of
//! `@armada/protocol`'s hand-written restatement, which drifts the day a field moves.
//!
//! Only the closure of [`ROOTS`] is written: each type Pocket imports, and every type those name.
//! A type Pocket starts reading is added to the list, and `tsc` says when one is missing.
//!
//! **The generator reads the source and not the compiled types**, with no dependency, like every other
//! task here, so it runs on a checkout with nothing built and `crates/ipc` gains no dependency and no
//! attribute. What it does not understand it refuses by name: a type with no `Serialize` derive, a
//! `rename_all` rule it has no reading of, a name nothing defines.
//!
//! One TypeScript file per Rust source file, in source order, and `index.ts` re-exporting all of them.
//! `cargo xtask verify-wire --write` regenerates, and `verify-foundations` fails a stale copy.

