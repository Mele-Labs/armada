-- The ready preview offers another Mac shares with this one, each whole as the wire carried it and opaque here, keyed
-- by the branch, so a Mac that is asleep still has its offers named after Fleet restarts. Additive.
-- docs/practices/store-migrations.md.
CREATE TABLE other_mac_preview_offers (
    mac   TEXT NOT NULL,
    id    TEXT NOT NULL,
    offer TEXT NOT NULL,
    PRIMARY KEY (mac, id)
) STRICT;
